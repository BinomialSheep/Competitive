struct Point {
  ll x, y;
};

long long calculateContributions(vector<int>& coords) {
  sort(coords.begin(), coords.end());
  long long totalContribution = 0;
  long long prefixSum = 0;
  int n = coords.size();

  for (int i = 0; i < n; ++i) {
    totalContribution += (long long)i * coords[i] - prefixSum;
    prefixSum += coords[i];
  }

  prefixSum = 0;
  for (int i = n - 1; i >= 0; --i) {
    totalContribution += prefixSum - (long long)(n - 1 - i) * coords[i];
    prefixSum += coords[i];
  }

  return totalContribution;
}

long long chebyshevDistanceSum(vector<Point>& points) {
  vector<int> x_coords, y_coords;
  for (const auto& p : points) {
    x_coords.push_back(p.x);
    y_coords.push_back(p.y);
  }

  long long x_total = calculateContributions(x_coords);
  long long y_total = calculateContributions(y_coords);

  return max(x_total, y_total);
}

