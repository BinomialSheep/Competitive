// ランダムな文字列を生成する関数
void generate_random_string(char* str, int length) {
  static const char charset[] =
      "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";
  for (int i = 0; i < length; i++) {
    int key = rand() % (sizeof(charset) - 1);
    str[i] = charset[key];
  }
  str[length] = '\0';
}

// KMPアルゴリズムの部分一致テーブル（失敗関数）を計算
void compute_kmp_table(const string& S, vector<int>& kmp_table) {
  int n = S.size();
  kmp_table.resize(n);
  int j = 0;
  kmp_table[0] = 0;

  for (int i = 1; i < n; i++) {
    while (j > 0 && S[i] != S[j]) {
      j = kmp_table[j - 1];
    }
    if (S[i] == S[j]) {
      j++;
    }
    kmp_table[i] = j;
  }
}

// prefixとsuffixの一致を判定
vector<bool> prefix_suffix_match(const string& S) {
  int n = S.size();
  vector<int> kmp_table;
  compute_kmp_table(S, kmp_table);

  vector<bool> result(n + 1, false);
  int length = kmp_table[n - 1];

  while (length > 0) {
    result[length] = true;
    length = kmp_table[length - 1];
  }
  result[0] = true;  // 空のprefixとsuffixは常に一致

  return result;
}

